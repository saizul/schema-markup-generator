const DICT = { en, bn };

/**
 * Translates a UI key. Falls back to English, then to the key itself.
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 * @param {'en'|'bn'} [lang]
 */
export function t(key, params = {}, lang = 'en') {
  const s = DICT[lang]?.[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Translates a form label; unknown labels stay English. */
export function tl(label, lang = 'en') {
  return lang === 'bn' ? labelsBn[label] ?? label : label;
}

export const keys = (lang) => Object.keys(DICT[lang]);
